/*
|--------------------------------------------------------------------------
| Настройки на рекапа с данни (/danni)
|--------------------------------------------------------------------------
|
| Трите ключа тук съществуват заради РАЗЛИКАТА между двата режима на работа.
|
| Нормалният режим е един кръг на две седмици: кешът пази лимита, LLM-ът пише
| разказа, скоростта няма значение.
|
| Наваксването назад (`padok:race-data-recap --season=2024`) е седемдесет кръга
| наведнъж и всяко от тези три неща се обръща срещу нас — затова командата ги
| изключва сама. Виж GenerateRaceDataRecapCommand.
|
*/

return [

    /*
     * Кеширане на историческите отговори от OpenF1.
     *
     * При нормална работа е задължително: рекапът се преизчислява няколко пъти
     * (текст, поправка, ребилд), а сесията вече не се мени.
     *
     * При наваксване е вредно. `CACHE_STORE` по подразбиране е `database`, а
     * един уикенд е около 4 MB отговори, от които `intervals` сам е 3 MB. За
     * седемдесет кръга това са стотици мегабайти в таблицата `cache` — за
     * данни, които се четат точно по веднъж.
     */
    'cache_historical' => env('RACE_DATA_CACHE_HISTORICAL', true),

    /*
     * Свързаният разказ минава ли през LLM.
     *
     * Изключено, рекапът пада към шаблонните изречения — по-скучно, но вярно и
     * безплатно. При наваксване назад това е правилният избор: седемдесет
     * извиквания за текстове, които никой няма да прочете скоро.
     */
    'narrative_llm' => env('RACE_DATA_NARRATIVE_LLM', true),

    /*
     * Пауза в милисекунди между два кръга при наваксване.
     *
     * Безплатният тир на OpenF1 е 30 заявки в минута, платеният — 60. Един
     * рекап е около шестнайсет заявки, тоест без пауза седемдесет кръга биха
     * ударили лимита. Стойността е с резерв.
     */
    'backfill_pause_ms' => env('RACE_DATA_BACKFILL_PAUSE_MS', 2000),

];
