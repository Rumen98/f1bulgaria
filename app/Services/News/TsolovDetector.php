<?php

declare(strict_types=1);

namespace App\Services\News;

use Illuminate\Support\Str;

/**
 * Разпознава новини за Никола Цолов.
 *
 * Нарочно БЕЗ LLM. За конкретен човек точното съвпадение по фамилия е
 * по-добро от модел във всяко измерение: няма фалшиви попадения, не струва
 * нищо, не зависи от жив доставчик и дава един и същ резултат всеки път.
 * Моделът остава за това, в което е незаменим — превода и статията.
 *
 * ТЪРСИ САМО В ЗАГЛАВИЕТО. Първата версия гледаше и тялото и хвана
 * „2026 F2 championship standings after Monza Sprint Race" — статия, в
 * която той просто е ред от таблица. Всяко класиране и всеки списък с
 * резултати го съдържа, така че кътът му щеше да се напълни с таблици
 * вместо с истории. Заглавието е границата между „за него" и „споменат":
 * когато статията е за него, името е в заглавието.
 *
 * Цената е известна: „Red Bull junior completes first F1 test" без име в
 * заглавието се пропуска. За това има ръчен ключ в админ панела — по-добре
 * да се добави една статия на месец, отколкото секцията да е таблици.
 *
 * Работи върху ОРИГИНАЛНОТО заглавие (английски), защото се вика при
 * вземането, преди обогатяването. Кирилските форми са за източници на
 * български.
 */
class TsolovDetector
{
    /**
     * Фамилията стига — „Цолов" е достатъчно рядка, за да няма съименник в
     * автомобилния спорт. Личното име се проверява отделно само за пълнота.
     *
     * @var list<string>
     */
    private const NEEDLES = ['tsolov', 'цолов'];

    public function matchesTitle(?string $title): bool
    {
        if ($title === null || $title === '') {
            return false;
        }

        $haystack = Str::lower($title);

        foreach (self::NEEDLES as $needle) {
            // Границата на думата пази от съвпадение вътре в друга дума.
            if (preg_match('/(?<!\p{L})'.preg_quote($needle, '/').'/u', $haystack) === 1) {
                return true;
            }
        }

        return false;
    }
}
